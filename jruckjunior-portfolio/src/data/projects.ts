export type ProjectCategory = 'Motion' | 'Branding' | 'Photography'

// A paragraph (newlines are kept, *phrase* is emphasised) or a small all-caps subhead.
export type CaseStudyText = string | { subhead: string }

export interface CaseStudyMedia {
  src: string
  alt: string
  video?: boolean
  // Video only: play on click with sound and controls instead of autoplaying.
  controls?: boolean
  // Video with controls only: still autoplay muted on loop.
  autoplay?: boolean
  // Video only: still shown before playback starts.
  poster?: string
  // Width / height; lets items in a row share one height.
  ratio?: number
}

export type CaseStudySection =
  // Full-width image, optionally introduced by a heading and text.
  | { kind: 'wide'; image: string; alt: string; heading?: string; body?: CaseStudyText[] }
  // Text beside an image, image on the given side.
  | {
      kind: 'split'
      heading: string
      body: CaseStudyText[]
      image: string
      alt: string
      imageSide: 'left' | 'right'
    }
  // A block of text on its own.
  | { kind: 'text'; heading?: string; body: CaseStudyText[]; align?: 'center' }
  // One or more images/videos side by side, centred, at a shared height.
  // `zoom` lets images open full size when clicked (the ratio can then crop them).
  | { kind: 'row'; media: CaseStudyMedia[]; maxWidth?: string; zoom?: boolean }
  // A gallery of equal tiles cropped to one ratio, `columns` across (a short last row stays left).
  | { kind: 'grid'; media: CaseStudyMedia[]; columns: number; ratio: number; zoom?: boolean }
  // Masonry: side-by-side columns of uncropped images, each column listed top to bottom.
  | { kind: 'columns'; columns: CaseStudyMedia[][]; zoom?: boolean }

export interface Project {
  slug: string
  title: string
  client: string
  category: ProjectCategory
  year: string
  summary: string
  role: string
  image: string
  // When present, the detail page shows these instead of image + summary.
  sections?: CaseStudySection[]
}

